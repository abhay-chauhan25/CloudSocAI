import { useEffect, useState } from "react";

import { ApiError, api } from "../api/client";
import type { Analysis, TimelineItem } from "../api/types";
import { formatTime } from "../format";

type PanelState =
  | { status: "loading" }
  | { status: "none" }
  | { status: "ready"; analysis: Analysis }
  | { status: "error"; message: string };

/**
 * The advisory AI analysis of an incident. Everything the model wrote is
 * rendered as plain text, and the panel says clearly that it is generated,
 * may be wrong, and changed nothing.
 */
export function AnalysisPanel({
  incidentId,
  timeline,
}: {
  incidentId: string;
  timeline: TimelineItem[];
}) {
  const [state, setState] = useState<PanelState>({ status: "loading" });
  const [generating, setGenerating] = useState(false);
  const [generateError, setGenerateError] = useState<string | null>(null);

  useEffect(() => {
    const controller = new AbortController();
    setState({ status: "loading" });
    api.getAnalysis(incidentId, controller.signal).then(
      (analysis) => setState({ status: "ready", analysis }),
      (error: unknown) => {
        if (controller.signal.aborted) return;
        if (error instanceof ApiError && error.status === 404) setState({ status: "none" });
        else setState({ status: "error", message: (error as Error).message });
      },
    );
    return () => controller.abort();
  }, [incidentId]);

  async function generate() {
    setGenerating(true);
    setGenerateError(null);
    try {
      setState({ status: "ready", analysis: await api.createAnalysis(incidentId) });
    } catch (error) {
      setGenerateError(error instanceof ApiError ? error.message : "Something went wrong.");
    } finally {
      setGenerating(false);
    }
  }

  const events = new Map(timeline.map((item) => [item.event.event_id, item.event]));
  const analysis = state.status === "ready" ? state.analysis : null;
  const canGenerate = state.status === "none" || (analysis !== null && !analysis.is_current);

  return (
    <section className="analysis" aria-label="AI analysis">
      <div className="analysis-header">
        <h2>AI analysis</h2>
        <span className="badge advisory">Advisory</span>
        {canGenerate && (
          <button type="button" onClick={generate} disabled={generating}>
            {generating ? "Analysing…" : analysis ? "Regenerate" : "Generate analysis"}
          </button>
        )}
      </div>

      {generateError && (
        <p className="state state-error" role="alert">
          {generateError}
        </p>
      )}
      {state.status === "loading" && <p className="muted">Loading analysis…</p>}
      {state.status === "error" && <p className="muted">{state.message}</p>}
      {state.status === "none" && !generating && (
        <p className="muted">
          No analysis yet. Generating one sends this incident's evidence (not raw logs) to the
          configured AI provider.
        </p>
      )}

      {analysis && (
        <>
          <p className="disclaimer">
            Generated by {analysis.provider} ({analysis.model}) at {formatTime(analysis.created_at)}.
            It may be wrong: check every claim against the evidence. It did not change severity,
            risk, or ATT&amp;CK mappings, and no action was taken.
          </p>
          {!analysis.is_current && (
            <p className="state state-warning" role="status">
              The incident changed after this analysis was generated.
            </p>
          )}

          <p>{analysis.result.summary}</p>

          <h3>What happened</h3>
          <ol className="narrative">
            {analysis.result.attack_narrative.map((step, index) => (
              <li key={index}>
                {step.description}
                <div className="chips">
                  {step.event_ids.map((id) => {
                    const event = events.get(id);
                    return (
                      <span key={id} className="chip" title={id}>
                        {event ? `${event.event_name} · ${formatTime(event.timestamp)}` : id}
                      </span>
                    );
                  })}
                </div>
              </li>
            ))}
          </ol>

          <h3>Likely objective</h3>
          <p>
            {analysis.result.likely_objective}{" "}
            <span className="muted">(confidence: {analysis.result.objective_confidence})</span>
          </p>

          <h3>Investigate next</h3>
          <ul>
            {analysis.result.investigation_steps.map((step, index) => (
              <li key={index}>{step}</li>
            ))}
          </ul>

          {analysis.result.containment_suggestions.length > 0 && (
            <>
              <h3>Containment ideas</h3>
              <p className="muted">For a human to review. Nothing here was executed.</p>
              <ul>
                {analysis.result.containment_suggestions.map((step, index) => (
                  <li key={index}>{step}</li>
                ))}
              </ul>
            </>
          )}

          {analysis.result.benign_explanations.length > 0 && (
            <>
              <h3>Possible benign explanations</h3>
              <ul>
                {analysis.result.benign_explanations.map((item, index) => (
                  <li key={index}>{item}</li>
                ))}
              </ul>
            </>
          )}
        </>
      )}
    </section>
  );
}
